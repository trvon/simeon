#!/usr/bin/env python3
"""Generate src/static_embedding_unicode.inc for the StaticEmbedding WordPiece normalizer.

    python3 tools/static_embedding/gen_unicode_tables.py > src/static_embedding_unicode.inc

Tables mirror HuggingFace's BertNormalizer / BertPreTokenizer predicates on the Basic Multilingual
Plane: punctuation (P*), combining marks (Mn), whitespace (Zs), control/format (Cc, Cf), and a
fold map giving NFD-with-marks-removed plus lowercase for Latin, Greek and Cyrillic letters.
"""
import sys
import unicodedata

FOLD_RANGES = [(0x00C0, 0x052F), (0x1E00, 0x1FFF)]


def ranges(pred):
    out = []
    start = None
    for cp in range(0x10000):
        hit = pred(cp)
        if hit and start is None:
            start = cp
        elif not hit and start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0xFFFF))
    return out


def cat(cp):
    return unicodedata.category(chr(cp))


def emit_ranges(name, rs):
    print(f"constexpr CodepointRange {name}[] = {{")
    for a, b in rs:
        print(f"    {{0x{a:04X}, 0x{b:04X}}},")
    print("};")


def main() -> int:
    print(f"// Generated by tools/static_embedding/gen_unicode_tables.py (unicodedata {unicodedata.unidata_version}). Do not edit.")
    emit_ranges("kPunctuation", ranges(lambda cp: cat(cp).startswith("P")))
    emit_ranges("kCombiningMark", ranges(lambda cp: cat(cp) == "Mn"))
    emit_ranges("kSpaceSeparator", ranges(lambda cp: cat(cp) == "Zs"))
    emit_ranges("kControlOrFormat", ranges(lambda cp: cat(cp) in ("Cc", "Cf") and cp not in (0x09, 0x0A, 0x0D)))
    def emit_map(name, fn):
        print(f"constexpr FoldEntry {name}[] = {{")
        for lo, hi in FOLD_RANGES:
            for cp in range(lo, hi + 1):
                ch = chr(cp)
                if not unicodedata.category(ch).startswith("L"):
                    continue
                folded = fn(ch)
                if folded != ch:
                    utf8 = folded.encode("utf-8")
                    if len(utf8) > 7:
                        continue
                    bytes_ = ", ".join(f"0x{b:02X}" for b in utf8)
                    print(f"    {{0x{cp:04X}, {len(utf8)}, {{{bytes_}}}}},")
        print("};")

    def strip(ch):
        return "".join(c for c in unicodedata.normalize("NFD", ch) if unicodedata.category(c) != "Mn")

    emit_map("kFoldStripLower", lambda ch: strip(ch).lower())
    emit_map("kFoldLower", lambda ch: ch.lower())
    emit_map("kFoldStrip", strip)
    return 0


if __name__ == "__main__":
    sys.exit(main())
